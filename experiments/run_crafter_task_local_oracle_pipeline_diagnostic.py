from src.skills.crafter_task_plan_executor import CrafterTaskPlanExecutor
from src.utils.config import load_config, runtime_metadata


@dataclass
class _ActionQueue:
    actions: list[str]
    cursor: int = 0


class _ScriptedModuleExecutor:
    """Verifier action replay with the learner-facing public adapter only."""

    def __init__(
        self,
        module_id: str,
        adapter: CrafterEnvironmentAdapter,
        queue: _ActionQueue,
        target: Mapping[str, Any],
        progress_targets: tuple[Mapping[str, Any], ...],
    ) -> None:
        self.module_id = module_id
        self.adapter = adapter
        self.queue = queue
        self.target = dict(target)
        self.progress_targets = tuple(dict(item) for item in progress_targets)
        self.reset_before_execute = False
        self.last_steps = 0
        self.progress_reached = False
        self.call_count = 0
        self.last_progress_target: Mapping[str, Any] | None = None

    def _progress_is_reached(self, state: Mapping[str, Any], target: Mapping[str, Any]) -> bool:
        name = target.get("name")
        if name == "inventory_at_least":
            inventory = state.get("inventory")
            return isinstance(inventory, Mapping) and int(inventory.get(
                str(target["item"]), 0
            )) >= int(target["threshold"])
        if name == "crafter_world_object_setup":
            observed = state.get("world_object_setup")
            return isinstance(observed, (list, tuple)) and set(target["objects"]).issubset(set(observed))
        return False

    def execute(self, response: ImplementationResponse, current_state: Mapping[str, Any]):
        if response.module_id != self.module_id:
            raise ValueError("scripted executor received the wrong Module")
        if self.reset_before_execute:
            self.adapter.reset()
        progress_target = self.progress_targets[min(self.call_count, len(self.progress_targets) - 1)]
        self.last_progress_target = dict(progress_target)
        self.call_count += 1
        before_state = self.adapter.state()
        self.last_steps = 0
        self.progress_reached = self._progress_is_reached(before_state, progress_target)
        while not self.progress_reached and self.queue.cursor < len(self.queue.actions):
            if self.adapter.state()["episode_done"]:
                break
            action_name = self.queue.actions[self.queue.cursor]
            self.queue.cursor += 1
            action = self.adapter.environment.action_names.index(action_name)
            self.adapter.step(action)
            self.last_steps += 1
            self.progress_reached = self._progress_is_reached(self.adapter.state(), progress_target)
        after_state = self.adapter.state()
        self.progress_reached = self._progress_is_reached(after_state, progress_target)
        done = bool(after_state["episode_done"])
        if self.target.get("name") == "crafter_world_object_setup":
            return crafter_world_object_transition_result(
                before_state, after_state, self.target, done
            )
        return crafter_transition_result(
            before_state.get("inventory"), after_state.get("inventory"), self.target, done
        )


def _fixture_library(plan, scope):
    spt = SPT("spt:task-local-oracle-pipeline-fixture", "task_local_fixture", "v1", {"fixture": True})
    library = InMemoryQualifiedSkillLibrary(spt, QualificationConfig())
    mechanisms = []
    modules_by_step = {}
    for index, step in enumerate(plan.steps):
        request = step.request
        contract = ImplementationContract(
            request.input_capabilities, (), (dict(request.target_capability),), {}, {}, {}, scope
        )
        spi = SPI(
            f"spi:task-local-oracle:{step.step_id}", "task_local_fixture", spt.spt_id,
            spt.version, {"step_id": step.step_id}, request, contract, {"fixture": True}, {}, {},
        )
        module = library.qualify(spi, f"policy:task-local-oracle:{step.step_id}", 1, 1, 1)
        if module is None:
            raise RuntimeError(f"fixture Module qualification failed for {step.step_id}")
        modules_by_step[step.step_id] = module
        mechanisms.append(Mechanism(
            f"mechanism:task-local-oracle:{index}", request.input_capabilities, (),
            request.target_capability, scope, None, "confirmed",
        ))
    return library, InMemoryKnowledgeBank(mechanisms), modules_by_step


def _reference_actions(seed: int, max_steps: int, task_id: str) -> tuple[list[str], bool]:
    target = {
        "name": "inventory_at_least",
        "item": "stone" if task_id == "collect_stone" else "wood_pickaxe",
        "threshold": 1,
    }
    environment = CrafterEnvironmentAdapter(seed=int(seed), reward=False, length=int(max_steps))
    environment.reset()
    planner = RecordingReferencePlanner(environment, target, int(max_steps), True)
    if task_id == "collect_stone":
        # The private map is used only to generate a bounded verifier script.
        # All replayed actions still cross the public adapter boundary.
        reached = planner._step("noop")
        wood = planner._collect_item("tree", "wood", 3)
        reached = reached and bool(wood.target_achieved)
        reached = reached and planner._place_table()
        reached = reached and planner._step("make_wood_pickaxe")
        if reached:
            stone = planner._collect_item("stone", "stone", 1)
            reached = bool(stone.target_achieved)
    else:
        summary = planner.run()
        reached = bool(summary.target_achieved)
    actions = [environment.environment.action_names[action] for _, action in planner.samples]
    environment.close()
    return actions, reached


def run(config_path: str, output_path: str) -> dict:
    config = load_config(config_path)
    if config.get("formal_result") is not False or config.get("fixture_modules") is not True:
        raise ValueError("oracle Pipeline diagnostic requires formal_result=false and fixture_modules=true")
    output = Path(output_path)
    if output.exists():
        raise FileExistsError(f"refusing to overwrite {output}")
    candidate = load_config("configs/crafter_task_local_composition_candidate_v1.yaml")
    scope = {"environment": "crafter", "adapter": candidate["observation_interface"]}
    plan = build_crafter_task_plan(candidate, str(config["task_id"]), scope)
    library, bank, modules_by_step = _fixture_library(plan, scope)
    episodes = []
    start = time.perf_counter()
    for seed in config["seeds"]:
        actions, oracle_success = _reference_actions(
            int(seed), int(config["max_steps"]), str(config["task_id"])
        )
        environment = CrafterEnvironmentAdapter(seed=int(seed), reward=False, length=int(config["max_steps"]))
        queue = _ActionQueue(actions)
        executors = {}
        for step in plan.steps:
            module = modules_by_step[step.step_id]
            target = step.request.target_capability
            progress_targets = (dict(target),)
            if step.step_id == "gather_wood_1_a":
                progress_targets = tuple(
                    {"name": "inventory_at_least", "item": "wood", "threshold": threshold}
                    for threshold in (1, 2, 3)
                )
            executors[module.module_id] = _ScriptedModuleExecutor(
                module.module_id, environment, queue, target, progress_targets
            )
        plan_executor = CrafterTaskPlanExecutor(executors)
        evidence, feedback = [], []
        pipeline = InMemoryContinualLearningPipeline(
            bank, library, plan_executor.execute, evidence.append, feedback.append,
        )
        plan_executor.begin_episode()
        task_result, transitions, final_state = pipeline.run_task_plan(
            plan, (), scope, {"inventory": None, "world_object_setup": None}
        )
        episodes.append({
            "seed": int(seed),
            "oracle_action_script_success": oracle_success,
            "action_count": len(actions),
            "task_result": task_result,
            "step_ids_executed": [item.get("plan_step_id") for item in feedback],
            "target_achieved": [item.target_achieved for item in transitions],
            "execution_status": [item.execution_status for item in transitions],
            "progress_reached": [
                executors[item["module_id"]].progress_reached for item in feedback
            ],
            "script_cursor": queue.cursor,
            "module_ids": [item.get("module_id") for item in feedback],
            "module_invocation_counts": {
                module_id: executor.call_count
                for module_id, executor in executors.items()
                if executor.call_count
            },
            "episode_steps": environment.state()["step_count"],
            "final_public_state": dict(final_state),
            "knowledge_evidence_validities": [item.evidence_validity for item in evidence],
            "skill_feedback_count": len(feedback),
        })
        environment.close()
    result = {
        "status": config["status"],
        "formal_result": False,
        "config": config_path,
        "candidate_config": "configs/crafter_task_local_composition_candidate_v1.yaml",
        "git_commit": subprocess.check_output(["git", "rev-parse", "HEAD"], text=True).strip(),
        "metadata": runtime_metadata(config, "cpu"),
        "device": "cpu",
        "task_id": str(config["task_id"]),
        "plan_step_ids": [step.step_id for step in plan.steps],
        "fixture_modules": True,
        "oracle_action_script": True,
        "public_boundary_only": True,
        "episodes": episodes,
        "knowledge_evolution_updated": False,
        "formal_module_claim": False,
        "elapsed_seconds": time.perf_counter() - start,
        "diagnostic_note": config["diagnostic_note"],
    }
    output.mkdir(parents=True)
    (output / "result.json").write_text(json.dumps(result, indent=2) + "\n", encoding="utf-8")
    return result


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--config", default="configs/crafter_task_local_oracle_pipeline_diagnostic_v1.yaml")
    parser.add_argument("--output", default="results/crafter_task_local_oracle_pipeline_diagnostic_v1")
    args = parser.parse_args()
    print(json.dumps(run(args.config, args.output), indent=2))


if __name__ == "__main__":
    main()
