import json
import subprocess
import time
from dataclasses import dataclass
from pathlib import Path
from typing import Any, Mapping

from experiments.run_crafter_rgb_oracle_imitation_diagnostic import RecordingReferencePlanner
from src.continual_learning.contracts import InMemoryContinualLearningPipeline
from src.environments.crafter_adapter import CrafterEnvironmentAdapter
from src.environments.crafter_task_plan import build_crafter_task_plan
from src.environments.crafter_tasks import (
    crafter_transition_result,
    crafter_world_object_transition_result,
)
from src.knowledge.contracts import InMemoryKnowledgeBank, Mechanism
from src.skills.contracts import ImplementationContract, ImplementationResponse
