"""Run one Crafter task-local plan through the real Pipeline boundary.

The action script is generated by the verifier-side public-action-consistent
reference planner and replayed on a fresh learner-facing adapter. Modules are
fixture-qualified; no Policy training, qualification, Knowledge update, or
formal result is produced. The diagnostic checks same-episode state transfer,
public table setup confirmation, and feedback routing for a multi-step plan.
"""
from __future__ import annotations

